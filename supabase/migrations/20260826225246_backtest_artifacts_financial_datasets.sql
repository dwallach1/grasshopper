-- Match live ledger on xqungxapqicdmboniezz (already applied).
-- Idempotent: do not drop data. JSON artifacts live in payload_json.

alter table public.strategy_tests
  add column if not exists price_source text,
  add column if not exists window_start date,
  add column if not exists window_end date,
  add column if not exists symbols text[],
  add column if not exists params_json jsonb;

create table if not exists public.backtest_artifacts (
  id bigint generated by default as identity primary key,
  test_id bigint not null references public.strategy_tests(id) on delete cascade,
  thesis_id text references public.theses(id),
  artifact_kind text not null,
  title text not null,
  mime_type text not null default 'application/json',
  payload_json jsonb,
  storage_bucket text,
  storage_path text,
  source text not null default 'financial_datasets_mcp',
  created_at timestamptz not null default now(),
  constraint backtest_artifacts_kind_check check (
    artifact_kind = any (array[
      'summary_json'::text,
      'equity_curve'::text,
      'trades'::text,
      'daily_returns'::text,
      'params_json'::text,
      'price_source'::text,
      'chart_svg'::text
    ])
  )
);

create index if not exists backtest_artifacts_test_id_idx
  on public.backtest_artifacts (test_id, created_at desc);
create index if not exists backtest_artifacts_thesis_id_idx
  on public.backtest_artifacts (thesis_id);

alter table public.backtest_artifacts enable row level security;

revoke all on table public.backtest_artifacts from public, anon;
grant select on table public.backtest_artifacts to authenticated;
grant select, insert, update on table public.backtest_artifacts to quantanamo_worker;
grant all on table public.backtest_artifacts to service_role;

do $$
declare
  sequence_name text;
begin
  sequence_name := pg_get_serial_sequence('public.backtest_artifacts', 'id');
  if sequence_name is not null then
    execute format('grant usage, select, update on sequence %s to quantanamo_worker', sequence_name);
    execute format('grant usage, select on sequence %s to service_role', sequence_name);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'backtest_artifacts'
      and policyname = 'ledger_operator_select'
  ) then
    create policy ledger_operator_select
    on public.backtest_artifacts
    for select
    to authenticated
    using ((select public.is_ledger_operator()));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'backtest_artifacts'
      and policyname = 'quantanamo_worker_select'
  ) then
    create policy quantanamo_worker_select
    on public.backtest_artifacts
    for select
    to quantanamo_worker
    using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'backtest_artifacts'
      and policyname = 'quantanamo_worker_insert'
  ) then
    create policy quantanamo_worker_insert
    on public.backtest_artifacts
    for insert
    to quantanamo_worker
    with check (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'backtest_artifacts'
      and policyname = 'quantanamo_worker_update'
  ) then
    create policy quantanamo_worker_update
    on public.backtest_artifacts
    for update
    to quantanamo_worker
    using (true)
    with check (true);
  end if;
end $$;
